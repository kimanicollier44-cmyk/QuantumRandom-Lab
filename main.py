def _build_train():
    rows = []
    for _name, bits in _train_streams():
        bias, min_ent, abs_ac = measure_features(bits)
        rows.append((bias * 4.0, min_ent, abs_ac * 10.0,
                     model_label(bias, min_ent, abs_ac)))
    return rows


_CLASSIFIER_TRAIN = _build_train()


def _features(bias, min_ent, abs_ac):
    return (bias * 4.0, min_ent, abs_ac * 10.0)


def _dist(a, b):
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))


def classify_features(bias, min_ent, abs_ac, k=3):
    """kNN (k=3) source-quality classifier on measured features."""
    if not 0.0 <= bias <= 0.5:
        raise ValueError("bias must be in [0, 0.5]")
    if not 0.0 <= min_ent <= 1.0:
        raise ValueError("min-entropy per bit must be in [0, 1]")
    if not 0.0 <= abs_ac <= 1.0:
        raise ValueError("|autocorrelation| must be in [0, 1]")
    f = _features(bias, min_ent, abs_ac)
    ranked = sorted(_CLASSIFIER_TRAIN, key=lambda row: _dist(f, row[:3]))
    votes = {}
    for row in ranked[:k]:
        votes[row[3]] = votes.get(row[3], 0) + 1
    return max(sorted(votes), key=lambda lab: votes[lab])


def classify_source(bits, k=3):
    """Classify a measured bit stream: good / marginal / bad."""
    bias, min_ent, abs_ac = measure_features(bits)
    return classify_features(bias, min_ent, abs_ac, k=k)


def source_report():
    """The named teaching sources, measured and classified."""
    scenarios = {
        "hadamard_fair_source": hadamard_bits(FAIR_BITS),
        "slightly_biased_p47": biased_bits(BIASED_BITS, _theta_for_p1(0.47)),
        "heavily_biased_p25": biased_bits(BIASED_BITS, BIASED_THETA),
        "sticky_source": sticky_bits(FAIR_BITS, stick=0.8),
        "extracted_source": von_neumann_extract(
            biased_bits(EXTRACT_SOURCE_BITS)),
    }
    out = {}
    for name, bits in scenarios.items():
        bias, min_ent, abs_ac = measure_features(bits)
        out[name] = {
            "bias": round(bias, 6),
            "min_entropy_per_bit": round(min_ent, 6),
            "abs_autocorrelation": round(abs_ac, 6),
            "label": classify_source(bits),
            "model_label": model_label(bias, min_ent, abs_ac),
        }
    return out


