# ================================================================ 1. Statevector simulator
# A register of n <= 6 qubits is a list of 2^n complex amplitudes in
# pure Python. Gates are applied index-by-index (no matrices stored).
# Born probabilities are |amplitude|^2, and every sampling routine
# below draws against those probabilities with a SEEDED classical
# PRNG - the simulation's honesty label: the probabilities are
# quantum, the dice that sample them here are classical and seeded.

def _check_qubits(n):
    if not 1 <= n <= MAX_QUBITS:
        raise ValueError(f"qubit count must be in [1, {MAX_QUBITS}]")


def zero_state(n):
    """The |0...0> state of an n-qubit register."""
    _check_qubits(n)
    state = [0j] * (1 << n)
    state[0] = 1.0 + 0j
    return state


def apply_single(state, n, qubit, m00, m01, m10, m11):
    """Apply a 1-qubit gate [[m00, m01], [m10, m11]] to `qubit` in place."""
    _check_qubits(n)
    if not 0 <= qubit < n:
        raise ValueError("qubit index out of range")
    step = 1 << qubit
    for base in range(0, 1 << n, step * 2):
        for off in range(step):
            i0 = base + off
            i1 = i0 + step
            a0, a1 = state[i0], state[i1]
            state[i0] = m00 * a0 + m01 * a1
            state[i1] = m10 * a0 + m11 * a1
    return state


def hadamard_all(state, n):
    """H on every qubit: |0...0> -> uniform superposition."""
    s = 1.0 / math.sqrt(2.0)
    for q in range(n):
        apply_single(state, n, q, s, s, s, -s)
    return state


def rotate_y(state, n, qubit, theta):
    """Ry-style preparation rotation by angle 2*theta on one qubit.

    |0> -> cos(theta)|0> + sin(theta)|1>, so the Born probability of
    measuring 1 is sin^2(theta). theta = pi/4 is the fair coin.
    """
    c, s = math.cos(theta), math.sin(theta)
    return apply_single(state, n, qubit, c, -s, s, c)


def biased_qubit_state(theta):
    """Single-qubit state cos(theta)|0> + sin(theta)|1>."""
    return rotate_y(zero_state(1), 1, 0, theta)


def born_probabilities(state):
    """Born probabilities |amplitude|^2 for every basis state."""
    return [a.real * a.real + a.imag * a.imag for a in state]


def prob_one(state, n, qubit):
    """Marginal Born probability that `qubit` measures 1."""
    step = 1 << qubit
    return sum(p for i, p in enumerate(born_probabilities(state))
               if i & step)


def sample_basis_counts(state, n, shots, seed=DEFAULT_SEED):
    """Sample `shots` basis-state outcomes against Born probabilities.

    The probabilities come from the quantum state; the draws come
    from random.Random(seed) - a classical, seeded PRNG. That is
    what makes this a deterministic simulation, not a QRNG.
    """
    if shots <= 0:
        raise ValueError("shots must be positive")
    probs = born_probabilities(state)
    cdf = []
    acc = 0.0
    for p in probs:
        acc += p
        cdf.append(acc)
    rng = random.Random(seed)
    counts = [0] * (1 << n)
    for _ in range(shots):
        x = rng.random()
        lo, hi = 0, len(cdf) - 1
        while lo < hi:
            mid = (lo + hi) // 2
            if cdf[mid] < x:
                lo = mid + 1
            else:
                hi = mid
        counts[lo] += 1
    return counts


# ================================================================ 2. Bit sources
# Three labelled sources. (a) The Hadamard source: bits sampled from
# a uniform 4-qubit register's Born distribution. (b) The biased
# source: bits drawn against P(1) = sin^2(theta) from the rotated
# qubit state. (c) The PRNG contrast source: plain classical PRNG
# bits, labelled NOT quantum - included to prove the battery cannot
# tell classical pseudo-randomness from quantum randomness.

def hadamard_bits(count, seed=DEFAULT_SEED, n=4):
    """`count` fair bits sampled from an H-applied register (seeded)."""
    if count <= 0:
        raise ValueError("count must be positive")
    state = hadamard_all(zero_state(n), n)
    probs = born_probabilities(state)
    cdf = []
    acc = 0.0
    for p in probs:
        acc += p
        cdf.append(acc)
    rng = random.Random(seed)
    bits = []
    while len(bits) < count:
        x = rng.random()
        idx = 0
        while cdf[idx] < x:
            idx += 1
        for q in range(n):
            bits.append((idx >> q) & 1)
    return bits[:count]


def biased_bits(count, theta=BIASED_THETA, seed=DEFAULT_SEED):
    """`count` bits from the rotated-qubit source, P(1) = sin^2(theta).

    The probability is read off the simulated quantum state; the
    draws are seeded classical PRNG draws against it (simulation).
    """
    if count <= 0:
        raise ValueError("count must be positive")
    p1 = prob_one(biased_qubit_state(theta), 1, 0)
    rng = random.Random(seed)
    return [1 if rng.random() < p1 else 0 for _ in range(count)]


def prng_bits(count, seed=DEFAULT_SEED):
    """Classical PRNG contrast bits - labelled NOT quantum, ever."""
    if count <= 0:
        raise ValueError("count must be positive")
    rng = random.Random(seed)
    return [rng.getrandbits(1) for _ in range(count)]


def sticky_bits(count, stick=0.8, seed=DEFAULT_SEED):
    """A 'sticky' source: repeats the previous bit with prob `stick`.

    Unbiased on average but heavily autocorrelated - the teaching
    counterexample that passes the frequency test and fails runs /
    autocorrelation. Classical model, labelled as such.
    """
    if count <= 0:
        raise ValueError("count must be positive")
    if not 0.0 <= stick <= 1.0:
        raise ValueError("stick must be in [0, 1]")
    rng = random.Random(seed)
    bits = [rng.getrandbits(1)]
    for _ in range(count - 1):
        if rng.random() < stick:
            bits.append(bits[-1])
        else:
            bits.append(1 - bits[-1])
    return bits


# ================================================================ 3. Entropy accounting
# Shannon entropy H = -sum p log2 p (the average surprise) and
# min-entropy H_min = -log2(max p) (the worst-case surprise - the
# number a cautious engineer quotes, because an attacker bets on
# the most likely outcome). A fair bit carries 1.0 of both; the
# pi/6-biased bit carries H = 0.8113 but only H_min = 0.4150.

def shannon_entropy(probs):
    """Shannon entropy in bits of a probability distribution."""
    return -sum(p * math.log2(p) for p in probs if p > 0.0)


def min_entropy(probs):
    """Min-entropy in bits: -log2 of the largest probability."""
    if not probs:
        raise ValueError("empty distribution")
    return -math.log2(max(probs))


def bit_distribution(bits):
    """Empirical [P(0), P(1)] of a bit stream."""
    if not bits:
        raise ValueError("empty bit stream")
    ones = sum(bits)
    return [(len(bits) - ones) / len(bits), ones / len(bits)]


def bits_to_bytes(bits):
    """Pack bits MSB-first into byte values (trailing bits dropped)."""
    out = []
    for i in range(0, len(bits) - 7, 8):
        v = 0
        for b in bits[i:i + 8]:
            v = (v << 1) | b
        out.append(v)
    return out


def byte_distribution(bits):
    """Empirical distribution over the 256 byte values of a stream."""
    values = bits_to_bytes(bits)
    if not values:
        raise ValueError("need at least 8 bits for one byte")
    counts = [0] * 256
    for v in values:
        counts[v] += 1
    return [c / len(values) for c in counts]


def entropy_report(bits):
    """Per-bit and per-byte Shannon + min-entropy of a stream."""
    bd = bit_distribution(bits)
    yd = byte_distribution(bits)
    return {
        "n_bits": len(bits),
        "p_one": round(bd[1], 6),
        "bias": round(abs(bd[1] - 0.5), 6),
        "shannon_per_bit": round(shannon_entropy(bd), 6),
        "min_entropy_per_bit": round(min_entropy(bd), 6),
        "shannon_per_byte": round(shannon_entropy(yd), 6),
        "min_entropy_per_byte": round(min_entropy(yd), 6),
    }


# ================================================================ 4. Von Neumann extractor
# Von Neumann's 1951 trick: read a biased (but independent) coin in
# pairs. 01 -> 0, 10 -> 1, and 00 / 11 are discarded. Both kept
# patterns have probability p(1-p), so the output is exactly
# unbiased whatever p is - the price is yield: a pair is kept with
# probability 2p(1-p), so the expected output is p(1-p) bits per
# input bit (0.1875 at p = 0.25). Extraction removes bias; it does
# NOT remove correlation, and it creates no new entropy.

def von_neumann_extract(bits):
    """Unbiased bits from non-overlapping pairs of a biased stream."""
    out = []
    for i in range(0, len(bits) - 1, 2):
        a, b = bits[i], bits[i + 1]
        if a == 0 and b == 1:
            out.append(0)
        elif a == 1 and b == 0:
            out.append(1)
    return out


def pair_acceptance_rate(p):
    """Probability a pair survives extraction: 2p(1-p)."""
    return 2.0 * p * (1.0 - p)


def theoretical_yield(p):
    """Expected output bits per input bit: p(1-p)."""
    return p * (1.0 - p)


def extraction_report(theta=BIASED_THETA, count=EXTRACT_SOURCE_BITS,
                      seed=DEFAULT_SEED):
    """Measured vs theoretical extraction economics for one source."""
    p1 = prob_one(biased_qubit_state(theta), 1, 0)
    raw = biased_bits(count, theta, seed)
    out = von_neumann_extract(raw)
    return {
        "theta": round(theta, 6),
        "p_one": round(p1, 6),
        "input_bits": len(raw),
        "output_bits": len(out),
        "measured_yield_per_input_bit": round(len(out) / len(raw), 6),
        "theoretical_yield_per_input_bit": round(theoretical_yield(p1), 6),
        "pair_acceptance_measured": round(2.0 * len(out) / len(raw), 6),
        "pair_acceptance_theoretical": round(pair_acceptance_rate(p1), 6),
        "output_p_one": round(bit_distribution(out)[1], 6) if out else None,
    }


# ================================================================ 5. Randomness test battery
# A SIMPLIFIED NIST-style battery - labelled, in the open: four
# teaching tests in the spirit of NIST SP 800-22 with explicit
# thresholds, not the real 15-test suite, not at certification
# grade, and passing them certifies NOTHING (the PRNG contrast
# stream passes too). What the battery CAN do is catch a bad
# source: bias trips monobit + chi-square, stickiness trips runs +
# autocorrelation.

def monobit_frequency_test(bits):
    """Simplified NIST monobit: s_obs = |sum(2b-1)| / sqrt(n)."""
    n = len(bits)
    s_obs = abs(sum(2 * b - 1 for b in bits)) / math.sqrt(n)
    return {"test": "monobit_frequency", "statistic": round(s_obs, 4),
            "threshold": MONOBIT_Z_MAX, "passed": s_obs < MONOBIT_Z_MAX}


def runs_test(bits):
    """Simplified runs test: z of the run count vs its iid expectation."""
    n = len(bits)
    pi = sum(bits) / n
    if pi in (0.0, 1.0):
        return {"test": "runs", "statistic": None, "threshold": RUNS_Z_MAX,
                "passed": False}
    runs = 1 + sum(1 for i in range(1, n) if bits[i] != bits[i - 1])
    mu = 2.0 * n * pi * (1.0 - pi) + 1.0
    sigma = math.sqrt(2.0 * n * pi * (1.0 - pi))
    z = abs(runs - mu) / sigma
    return {"test": "runs", "statistic": round(z, 4),
            "threshold": RUNS_Z_MAX, "passed": z < RUNS_Z_MAX,
            "runs": runs, "expected_runs": round(mu, 2)}


def lag1_autocorrelation(bits):
    """Pearson lag-1 autocorrelation of the stream (mean-centred).

    Centring matters: an iid but biased stream has NO autocorrelation
    even though its mean is off-centre - bias is the monobit test's
    job; this test's job is correlation between neighbours.
    """
    n = len(bits)
    if n < 2:
        raise ValueError("need at least 2 bits")
    mean = sum(bits) / n
    den = sum((b - mean) ** 2 for b in bits)
    if den == 0.0:
        r = 0.0
    else:
        num = sum((bits[i] - mean) * (bits[i + 1] - mean)
                  for i in range(n - 1))
        r = num / den
    limit = AUTOCORR_Z / math.sqrt(n)
    return {"test": "lag1_autocorrelation", "statistic": round(r, 6),
            "threshold": round(limit, 6), "passed": abs(r) < limit}


def chi_square_bytes_test(bits):
    """Chi-square of the byte distribution against uniform (df 255)."""
    values = bits_to_bytes(bits)
    if len(values) < 256:
        raise ValueError("need at least 256 bytes for the chi-square test")
    counts = [0] * 256
    for v in values:
        counts[v] += 1
    expected = len(values) / 256.0
    chi2 = sum((c - expected) ** 2 / expected for c in counts)
    return {"test": "chi_square_bytes", "statistic": round(chi2, 2),
            "threshold": CHI2_BYTES_MAX, "passed": chi2 < CHI2_BYTES_MAX,
            "n_bytes": len(values)}


def run_battery(bits, quantum):
    """Full simplified battery + the honesty label for the source.

    `quantum` records what the source CLAIMS to be in this lab's
    bookkeeping: True only for streams sampled from the simulated
    quantum state's Born probabilities. Passing is about statistics,
    never about quantumness - the PRNG stream passes with False.
    """
    tests = [monobit_frequency_test(bits), runs_test(bits),
             lag1_autocorrelation(bits), chi_square_bytes_test(bits)]
    return {"n_bits": len(bits), "quantum_source": bool(quantum),
            "tests": tests,
            "passed": all(t["passed"] for t in tests),
            "note": "simplified teaching battery - passing certifies nothing"}


def battery_book():
    """The four teaching streams, each run through the battery."""
    fair = hadamard_bits(FAIR_BITS)
    biased = biased_bits(BIASED_BITS)
    extracted = von_neumann_extract(biased_bits(EXTRACT_SOURCE_BITS))
    prng = prng_bits(FAIR_BITS)
    return {
        "hadamard_fair": run_battery(fair, quantum=True),
        "biased_raw": run_battery(biased, quantum=True),
        "biased_after_von_neumann": run_battery(extracted, quantum=True),
        "prng_contrast_NOT_quantum": run_battery(prng, quantum=False),
    }


# ================================================================ 6. kNN source classifier
# Features: (bias x 4, min-entropy per bit, |lag-1 autocorrelation|
# x 10). The labels come from the battery itself, distilled into
# model_label: a source the battery would wave through on every
# axis is "good"; one that trips the hard lines (bias >= 0.08,
# min-entropy <= 0.80 bits, |autocorrelation| >= 0.08) is "bad";
# anything in between is "marginal". Training rows are measured
# from real streams in this lab and labelled by that same rule.

def measure_features(bits):
    """(bias, min_entropy_per_bit, |lag-1 autocorrelation|) of a stream."""
    rep = entropy_report(bits)
    ac = lag1_autocorrelation(bits)["statistic"]
    return (rep["bias"], rep["min_entropy_per_bit"], abs(ac))


def model_label(bias, min_ent, abs_ac):
    """Ground-truth source label distilled from the battery's lines."""
    if bias >= 0.08 or min_ent <= 0.80 or abs_ac >= 0.08:
        return "bad"
    if bias <= 0.02 and min_ent >= 0.97 and abs_ac <= 0.02:
        return "good"
    return "marginal"


def _theta_for_p1(p1):
    return math.asin(math.sqrt(p1))


