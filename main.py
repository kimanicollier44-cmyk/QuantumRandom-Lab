# ================================================================ checks
def run_checks():
    c = []

    def chk(name, ok):
        c.append((name, bool(ok)))

    # 1. statevector simulator - Born probabilities are the physics
    st = hadamard_all(zero_state(3), 3)
    probs = born_probabilities(st)
    chk("state_normalised_after_hadamard", abs(sum(probs) - 1.0) < 1e-12)
    chk("hadamard_uniform_probabilities",
        all(abs(p - 1.0 / 8.0) < 1e-12 for p in probs))
    chk("hadamard_prob_one_half_each_qubit",
        all(abs(prob_one(st, 3, q) - 0.5) < 1e-12 for q in range(3)))
    chk("zero_state_probabilities",
        born_probabilities(zero_state(2)) == [1.0, 0.0, 0.0, 0.0])
    chk("biased_prob_one_pi_over_6",
        abs(prob_one(biased_qubit_state(BIASED_THETA), 1, 0) - 0.25) < 1e-12)
    chk("fair_theta_prob_one_half",
        abs(prob_one(biased_qubit_state(FAIR_THETA), 1, 0) - 0.5) < 1e-12)
    chk("biased_prob_monotone_in_theta",
        prob_one(biased_qubit_state(0.3), 1, 0)
        < prob_one(biased_qubit_state(0.6), 1, 0)
        < prob_one(biased_qubit_state(0.9), 1, 0))
    try:
        zero_state(MAX_QUBITS + 1)
        chk("max_qubits_guard", False)
    except ValueError:
        chk("max_qubits_guard", True)
    counts = sample_basis_counts(st, 3, 8000)
    chk("sampling_counts_sum_to_shots", sum(counts) == 8000)
    chk("sampling_same_seed_deterministic",
        sample_basis_counts(st, 3, 500) == sample_basis_counts(st, 3, 500))
    chk("sampling_uniform_roughly_even",
        all(700 < x < 1300 for x in counts))
    bcounts = sample_basis_counts(biased_qubit_state(BIASED_THETA), 1, 8192)
    chk("sampling_biased_skewed",
        abs(bcounts[1] / 8192.0 - 0.25) < 0.03)
    # 2. entropy accounting - analytic values first, then measured
    chk("shannon_uniform_byte_is_8",
        abs(shannon_entropy([1.0 / 256.0] * 256) - 8.0) < 1e-9)
    chk("min_entropy_uniform_byte_is_8",
        abs(min_entropy([1.0 / 256.0] * 256) - 8.0) < 1e-9)
    chk("shannon_fair_bit_is_1", shannon_entropy([0.5, 0.5]) == 1.0)
    chk("min_entropy_biased_bit_value",
        abs(min_entropy([0.75, 0.25]) - 0.415037) < 1e-6)
    fair = hadamard_bits(FAIR_BITS)
    biased = biased_bits(BIASED_BITS)
    fair_rep = entropy_report(fair)
    biased_rep = entropy_report(biased)
    chk("uniform_stream_shannon_per_byte_high",
        fair_rep["shannon_per_byte"] > 7.9)
    chk("biased_stream_min_entropy_lower",
        biased_rep["min_entropy_per_byte"] < fair_rep["min_entropy_per_byte"]
        and biased_rep["min_entropy_per_bit"] < fair_rep["min_entropy_per_bit"])
    chk("entropy_ordering_fair_above_biased",
        fair_rep["shannon_per_bit"] > biased_rep["shannon_per_bit"])
    chk("biased_stream_bias_measured",
        abs(biased_rep["bias"] - 0.25) < 0.02)
    # 3. von Neumann extractor - mapping, yield, unbiasedness
    chk("von_neumann_pair_mapping",
        von_neumann_extract([0, 1, 1, 0, 0, 0, 1, 1]) == [0, 1])
    chk("von_neumann_constant_stream_empty",
        von_neumann_extract([0] * 100) == [])
    chk("theoretical_yield_at_p25",
        abs(theoretical_yield(0.25) - 0.1875) < 1e-12)
    chk("pair_acceptance_at_p25",
        abs(pair_acceptance_rate(0.25) - 0.375) < 1e-12)
    ext = extraction_report()
    chk("measured_yield_matches_theory",
        abs(ext["measured_yield_per_input_bit"]
            - ext["theoretical_yield_per_input_bit"]) < 0.02)
    chk("extracted_output_unbiased",
        ext["output_p_one"] is not None
        and abs(ext["output_p_one"] - 0.5) < 0.03)
    chk("extraction_shortens_stream", ext["output_bits"] < ext["input_bits"])
    # 4. the battery - biased raw fails, extraction fixes it, PRNG is labelled
    book = battery_book()
    chk("battery_fair_passes", book["hadamard_fair"]["passed"])
    chk("battery_biased_raw_fails_frequency",
        not book["biased_raw"]["tests"][0]["passed"])
    chk("battery_biased_raw_fails_overall", not book["biased_raw"]["passed"])
    chk("battery_biased_chi_square_trips",
        not book["biased_raw"]["tests"][3]["passed"])
    chk("battery_extracted_passes",
        book["biased_after_von_neumann"]["passed"])
    chk("battery_prng_passes_but_not_quantum",
        book["prng_contrast_NOT_quantum"]["passed"]
        and book["prng_contrast_NOT_quantum"]["quantum_source"] is False)
    sticky = sticky_bits(FAIR_BITS, stick=0.8)
    chk("sticky_fails_autocorrelation",
        not lag1_autocorrelation(sticky)["passed"])
    chk("sticky_fails_runs", not runs_test(sticky)["passed"])
    chk("monobit_threshold_explicit",
        monobit_frequency_test(biased)["statistic"] > MONOBIT_Z_MAX)
    # 5. classifier - agrees with the battery-distilled model
    rep = source_report()
    chk("classifier_fair_good", rep["hadamard_fair_source"]["label"] == "good")
    chk("classifier_slight_bias_marginal",
        rep["slightly_biased_p47"]["label"] == "marginal")
    chk("classifier_heavy_bias_bad",
        rep["heavily_biased_p25"]["label"] == "bad")
    chk("classifier_sticky_bad", rep["sticky_source"]["label"] == "bad")
    chk("classifier_extracted_good",
        rep["extracted_source"]["label"] == "good")
    chk("classifier_matches_model",
        all(row["label"] == row["model_label"] for row in rep.values()))
    chk("classifier_training_labels_match_model",
        all(model_label(row[0] / 4.0, row[1], row[2] / 10.0) == row[3]
            for row in _CLASSIFIER_TRAIN))
    # gates + seats
    chk("hold_gates_14", len(HOLD_GATES) == 14
        and all(v.startswith("HOLD") for v in HOLD_GATES.values()))
    chk("gate_certified_qrng_hold", gate("certified_qrng_claim") == "HOLD")
    chk("gate_crypto_keys_hold", gate("cryptographic_key_generation") == "HOLD")
    chk("gate_gambling_hold", gate("gambling_lottery_claim") == "HOLD")
    chk("gate_beacon_hold", gate("randomness_beacon_operation") == "HOLD")
    chk("gate_seeded_as_quantum_hold",
        gate("seeded_output_as_quantum_claim") == "HOLD")
    chk("gate_sandbox_proceed", gate("run_simulation") == "PROCEED")
    b = brains_report()
    chk("argon4_no_override", b["decider"]["can_override_hold"] is False)
    chk("argon4_seat_id", b["decider"]["seat"].startswith("Gemini Argon 4"))
    chk("claude_no_override", b["advisor"]["can_override_hold"] is False)
    chk("flow_plan_only", b["flow"]["rendered"] is False and b["flow"]["live"] == 0)
    return c


